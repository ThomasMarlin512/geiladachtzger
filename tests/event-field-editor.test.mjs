import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fieldPatch,eventFieldSpecs,programFieldSpecs} from '../event-field-editor.js';
import {travelCards,travelTimeline,albumCard} from '../event-layout.js';
import {programCards,programTimeline} from '../trip-program.js';
assert.deepEqual(fieldPatch('event','outbound_time',{outbound_time:''}),{outbound_time:null});
assert.deepEqual(fieldPatch('event','description',{description:'  Treffpunkt\nBürs  '}),{description:'Treffpunkt\nBürs'});
assert.throws(()=>fieldPatch('event','title',{title:'x'}));
assert.throws(()=>fieldPatch('event','description',{description:'x'.repeat(2001)}));
for(const url of ['javascript:alert(1)','http://example.com','https://user:pass@example.com'])assert.throws(()=>fieldPatch('event','hotel_url',{hotel_url:url}));
assert.equal(fieldPatch('event','hotel_url',{hotel_url:'https://example.com'}).hotel_url,'https://example.com/');
assert.throws(()=>fieldPatch('event','status',{status:'confirmed'}));
assert.throws(()=>fieldPatch('event','hotel_status',{hotel_status:'bad'}));
const schedule={day_number:'2',start_time:'23:00',end_time:'01:00',ends_next_day:true,time_label:'danach'};
assert.equal(fieldPatch('program','schedule',schedule).day_number,2);
assert.throws(()=>fieldPatch('program','schedule',{...schedule,ends_next_day:false}));
assert.throws(()=>fieldPatch('program','schedule',{...schedule,day_number:'32'}));
assert.throws(()=>fieldPatch('program','schedule',{...schedule,start_time:''}));
const event={id:'new-event',title:'Neu',description:'Text',start_date:null,outbound_time:'09:00:00',outbound_details:'Bürs',album_url:'https://example.com/album'};
const markup=travelCards(event)+travelTimeline(event)+albumCard(event,false);
for(const field of Object.keys(eventFieldSpecs).filter(f=>!['title','location','description','website_url'].includes(f)))assert(markup.includes('data-event-field="'+field+'"'),field);
const item={id:'item',event_id:'new-event',title:'<script>',description:'Beschreibung',time_label:'Hinweis',category:'activity',day_number:1};
const cards=programCards([item],[],[],event,'member',()=>'',1),timeline=programTimeline([item],event);
for(const field of ['schedule','title','description','cost_label','website_url'])assert(cards.includes('data-program-field="'+field+'"'));
for(const field of ['schedule','title','description','time_label'])assert(timeline.includes('data-program-field="'+field+'"'));
assert(cards.includes('data-program-id="item"'));assert(timeline.includes('data-program-id="item"'));assert(!cards.includes('<script>'));
const app=readFileSync(new URL('../app.js',import.meta.url),'utf8');
for(const field of ['title','location','description','website_url'])assert(app.includes('data-event-field="'+field+'"'));
console.log('PASS: field validation, nullable times, secure links, date rules, and shared new-event edit targets');

assert.equal(fieldPatch('program','category',{category:'food'}).category,'food');
assert.throws(()=>fieldPatch('program','category',{category:'invalid'}));
